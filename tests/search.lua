local notes = require("neorg.modules.external.indexer.search_notes")
local query = require("neorg.modules.external.indexer.search_query")
local search_index = require("neorg.modules.external.indexer.search_index")

local function texts(...)
    return vim.tbl_map(notes.text, { ... })
end

local function write(path, lines)
    vim.fn.mkdir(vim.fn.fnamemodify(path, ":h"), "p")
    vim.fn.writefile(lines, path)
end

local function index_tests()
    local root = vim.fn.tempname()
    local config = {
        name = "index.norg",
        search = { search_content = true, include_generated = false },
        categories = { enabled = true, dir = "categories", subcategory_separator = "/", per_subcategory_index = true },
        authors = { enabled = true, dir = "authors", per_author_index = true },
        created = { enabled = true, dir = "created", per_period_index = true },
        updated = { enabled = true, dir = "updated", per_period_index = false },
        bibtex = { keyword = { enabled = true, dir = "keywords", per_value_index = true } },
    }
    local bibtex_dirs = {}
    for _, field in ipairs(require("neorg.modules.external.indexer.indexers").bibtex_fields) do
        bibtex_dirs[#bibtex_dirs + 1] = field.name == "keyword" and "keywords" or ("index/bibtex/" .. field.name)
    end
    assert(vim.deep_equal(
        search_index.generated_paths(config),
        vim.list_extend({ "index.norg", "categories", "authors", "created", "updated" }, bibtex_dirs)
    ))
    -- Nothing is indexed yet.
    assert(vim.tbl_isempty(search_index.read(root, config)))

    write(root .. "/categories/dev.norg", {
        "@document.meta", "title: dev", "categories: [", "  meta-only", "]", "@end",
        "* dev", "", "** {:dev/research:}[research]", "** {:../index:}[󰜱 index]", "",
        "* Notes", "", "** {:$/topic:}[Topic]", "** {:$/other:}[Other]",
    })
    write(root .. "/categories/dev/research.norg", {
        "* research", "", "** {:$/topic:}[Topic]", "** {:../dev:}[󰜱 dev]",
    })
    write(root .. "/authors/A=2FB.norg", { "* A/B", "", "** {:$/topic:}[Topic]", "** {:../index:}[󰜱 index]" })
    write(root .. "/created/2024.norg", { "* 2024", "", "** {:2024/02:}[2024-02]", "* Notes", "** {:$/topic:}[Topic]" })
    write(root .. "/created/2024/02.norg", { "* 2024-02", "", "** {:02/29:}[2024-02-29]", "** {:../2024:}[󰜱 2024]" })
    write(root .. "/created/2024/02/29.norg", { "* 2024-02-29", "", "** {:$/topic:}[Topic]" })
    write(root .. "/index.norg", {
        "* Index", "", "** Categories", "*** {:categories/dev:}[dev]", "*** {:$/stray:}[Stray]", "",
        "** Updated", "*** 2025", "**** 2025-03", "***** {:$/topic:}[Topic]",
        [=[***** {/ literature/k]1.bib}[\[k\]1\] T \[x\]] {/ literature/k]1.pdf}[\[PDF\]]]=],
        "**** {:$/other:}[Other]",
    })
    -- Literature lines: escaped "[citekey]" prefix and "[PDF]" link, relative to the index file.
    write(root .. "/keywords/Lossless.norg", {
        "* Lossless", "", [=[** {/ ../literature/k]1.bib}[\[k\]1\] T \[x\]] {/ ../literature/k]1.pdf}[\[PDF\]]]=],
        [=[** {/ ../literature/nopdf.bib}[\[nopdf\] No PDF]]=], "** {:../index:}[󰜱 index]",
    })
    -- Bucket files are only read from directories generated by the indexer.
    for _, dir in ipairs({ "categories", "authors", "created", "keywords" }) do
        write(root .. "/" .. dir .. "/.neorg-indexer", {})
    end
    local metadata = search_index.read(root, config)
    assert(vim.tbl_contains(search_index.generated_paths(config, root), "authors"))
    -- Without the marker, a directory holds user notes: not read, not excluded from search.
    vim.fn.delete(root .. "/authors/.neorg-indexer")
    assert(search_index.read(root, config)["topic.norg"].authors == nil)
    assert(not vim.tbl_contains(search_index.generated_paths(config, root), "authors"))
    -- A missing directory is still excluded.
    assert(vim.tbl_contains(search_index.generated_paths(config, root .. "/missing"), "authors"))
    vim.fn.delete(root, "rf")
    assert(vim.deep_equal(metadata["topic.norg"], {
        categories = texts("dev/research"),
        authors = texts("A/B"),
        created = texts("2024-02-29"),
        updated = texts("2025-03"),
    }), vim.inspect(metadata["topic.norg"]))
    assert(vim.deep_equal(metadata["other.norg"], { categories = texts("dev"), updated = texts("2025") }))
    assert(vim.deep_equal(metadata["literature/k]1.bib"], {
        ["bibtex.keyword"] = texts("Lossless"),
        updated = texts("2025-03"),
    }), vim.inspect(metadata["literature/k]1.bib"]))
    assert(vim.deep_equal(metadata["literature/nopdf.bib"], { ["bibtex.keyword"] = texts("Lossless") }))
    assert(metadata["literature/k]1.pdf"] == nil)
    -- Per-file indexers ignore the main index sections.
    assert(metadata["stray.norg"] == nil)
end

-- Picker entries: a literature with a PDF gets a PDF entry right after its rows.
local function picker_tests()
    local picker = require("neorg.modules.external.indexer.search_picker")
    local root = "/ws"
    local function literature(relative, title, pdf, body)
        local lines = {}
        for i, line in ipairs(body or {}) do
            lines[i] = notes.text(line)
            lines[i].lnum = i
        end
        return {
            kind = "literature",
            path = root .. "/" .. relative,
            relative = relative,
            title = notes.text(title),
            pdf = pdf,
            body = lines,
            metadata = { authors = texts("Ada Lovelace") },
        }
    end
    local snapshot = {
        literature("lit/a.bib", "[a2020] Lossless delay", root .. "/papers/a.pdf", {
            "@article{a2020,",
            "  note = {lossless},",
        }),
        literature("lit/b.bib", "[b2021] Lossless network", nil, { "@article{b2021," }),
        literature("lit/c.bib", "[c2022] Other", vim.fn.expand("~") .. "/outside/c.pdf", { "  note = {lossless}," }),
        {
            kind = "note",
            path = root .. "/note.norg",
            relative = "note.norg",
            title = notes.text("lossless"),
            body = {},
            metadata = {},
        },
    }
    local function rows(prompt, content)
        local result = {}
        for _, entry in ipairs(picker.entries(root, snapshot, query.parse(prompt), content)) do
            local text = entry.display(entry)
            result[#result + 1] = text
            if entry.pdf then
                -- PDF entries point to the PDF, but preview and paths use the .bib file.
                assert(entry.pdf == entry.value.pdf and entry.path == entry.value.path and not entry.lnum)
                assert(entry.ordinal:find("pdf", 1, true), entry.ordinal)
            end
        end
        return result
    end
    local function check(prompt, content, expected)
        local actual = rows(prompt, content)
        assert(vim.deep_equal(actual, expected), prompt .. ": " .. vim.inspect(actual))
    end
    check("lossless", false, {
        "lit/a.bib:[a2020] Lossless delay",
        "papers/a.pdf:[PDF]:[a2020] Lossless delay",
        "lit/b.bib:[b2021] Lossless network",
        "note.norg:lossless",
    })
    -- Body rows come first, then the PDF entry; title matches still rank first.
    check("lossless | content:lossless", true, {
        "lit/a.bib:[a2020] Lossless delay",
        "lit/a.bib:2:  note = {lossless},",
        "papers/a.pdf:[PDF]:[a2020] Lossless delay",
        "lit/b.bib:[b2021] Lossless network",
        "note.norg:lossless",
        "lit/c.bib:1:  note = {lossless},",
        "~/outside/c.pdf:[PDF]:[c2022] Other",
    })
    -- Metadata hits are shown on the PDF entry too.
    check("author:ada a2020", false, {
        "lit/a.bib:[authors: Ada Lovelace]:[a2020] Lossless delay",
        "papers/a.pdf:[PDF]:[authors: Ada Lovelace]:[a2020] Lossless delay",
    })
    check("network", false, { "lit/b.bib:[b2021] Lossless network" })
    check("missing", false, {})
    check("", false, {})
    local entry = picker.entries(root, snapshot, query.parse("a2020"), false)[2]
    local text, highlights = entry.display(entry)
    local range = highlights[1][1]
    assert(#highlights == 1 and text:sub(range[1] + 1, range[2]) == "a2020", vim.inspect(highlights))
end

-- PDF previews: options, cache keys, the ImageMagick command, and asynchronous conversion.
local function pdf_preview_tests()
    local pdf_preview = require("neorg.modules.external.indexer.pdf_preview")
    assert(pdf_preview.options(false) == nil and pdf_preview.options({ enabled = false }) == nil)
    assert(vim.deep_equal(pdf_preview.options(true), { density = 110 }))
    assert(vim.deep_equal(pdf_preview.options(nil), { density = 110 }))
    assert(vim.deep_equal(pdf_preview.options({ enabled = true, density = 200 }), { density = 200 }))
    assert(vim.deep_equal(pdf_preview.options({ density = -1 }), { density = 110 }))

    local stat = { mtime = { sec = 1, nsec = 2 }, size = 3 }
    local path = pdf_preview.cache_path("/a.pdf", stat, 110)
    assert(path:match("/neorg%-indexer/pdf%-preview/%x+%.png$"), path)
    assert(path:sub(1, #vim.fn.stdpath("cache")) == vim.fn.stdpath("cache"))
    assert(path == pdf_preview.cache_path("/a.pdf", vim.deepcopy(stat), 110))
    for _, other in ipairs({
        pdf_preview.cache_path("/b.pdf", stat, 110),
        pdf_preview.cache_path("/a.pdf", { mtime = { sec = 1, nsec = 3 }, size = 3 }, 110),
        pdf_preview.cache_path("/a.pdf", { mtime = { sec = 1, nsec = 2 }, size = 4 }, 110),
        pdf_preview.cache_path("/a.pdf", stat, 120),
    }) do
        assert(other ~= path)
    end
    assert(vim.deep_equal(pdf_preview.command("magick", "/a b.pdf", "/c.png", 110), {
        "magick", "-density", "110", "/a b.pdf[0]", "-background", "white", "-alpha", "remove", "png:/c.png",
    }))

    local root = vim.fn.tempname()
    local cache_dir, converter, system = pdf_preview.cache_dir, pdf_preview.converter, vim.system
    pdf_preview.cache_dir = function()
        return root .. "/cache"
    end
    local pdf = root .. "/a.pdf"
    write(pdf, { "%PDF-1.4" })
    local commands, exits = {}, {}
    vim.system = function(cmd, _, on_exit)
        commands[#commands + 1] = cmd
        exits[#exits + 1] = on_exit
        return {}
    end
    local function finish(i, code, stderr)
        if code == 0 then
            write(commands[i][#commands[i]]:sub(5), { "png" })
        end
        -- vim.system calls on_exit outside the main loop.
        vim.uv.new_timer():start(0, 0, function()
            exits[i]({ code = code, stderr = stderr })
        end)
    end
    local results = {}
    local function rasterize(name, target)
        pdf_preview.rasterize(target or pdf, { density = 110 }, function(png, err)
            results[#results + 1] = { name, png, err }
        end)
    end
    local function await(count)
        assert(vim.wait(2000, function()
            return #results == count
        end), vim.inspect(results))
    end
    local ok, err = pcall(function()
        pdf_preview.reset()
        pdf_preview.converter = function()
            return nil
        end
        rasterize("missing")
        assert(#results == 0, "the callback ran synchronously")
        await(1)
        assert(results[1][2] == nil and results[1][3] == "ImageMagick is not installed" and #commands == 0)
        assert(pdf_preview.available() == nil)
        pdf_preview.converter = function()
            return "magick"
        end
        -- Concurrent requests share one conversion.
        rasterize("first")
        rasterize("second")
        assert(#commands == 1 and commands[1][1] == "magick" and commands[1][4] == pdf .. "[0]")
        local png = pdf_preview.cache_path(pdf, vim.uv.fs_stat(pdf), 110)
        assert(commands[1][#commands[1]]:match("^png:" .. vim.pesc(png) .. "%.%d+%.tmp$"))
        finish(1, 0)
        await(3)
        assert(vim.deep_equal(results[2], { "first", png }) and vim.deep_equal(results[3], { "second", png }))
        assert(vim.fn.filereadable(png) == 1 and #vim.fn.glob(root .. "/cache/*.tmp", false, true) == 0)
        -- The cached PNG is reused.
        rasterize("cached")
        await(4)
        assert(results[4][2] == png and #commands == 1)
        -- A changed PDF is converted again; failures are reported, not cached, and retried.
        write(pdf, { "%PDF-1.4", "changed" })
        rasterize("failed")
        assert(#commands == 2)
        finish(2, 1, "gs: command not found\n")
        await(5)
        assert(results[5][2] == nil and results[5][3] == "gs: command not found", vim.inspect(results[5]))
        assert(#vim.fn.glob(root .. "/cache/*", false, true) == 1)
        rasterize("failed again")
        assert(#commands == 3)
        -- An empty output is a failure too, and is not cached.
        write(commands[3][#commands[3]]:sub(5), {})
        vim.uv.new_timer():start(0, 0, function()
            exits[3]({ code = 0, stderr = "" })
        end)
        await(6)
        assert(results[6][2] == nil and results[6][3] == "ImageMagick exited with code 0", vim.inspect(results[6]))
        assert(#vim.fn.glob(root .. "/cache/*", false, true) == 1)
        rasterize("retried")
        assert(#commands == 4)
        finish(4, 0)
        await(7)
        local changed = pdf_preview.cache_path(pdf, vim.uv.fs_stat(pdf), 110)
        assert(results[7][2] == changed and vim.fn.filereadable(changed) == 1, vim.inspect(results[7]))
        rasterize("unreadable", root .. "/missing.pdf")
        await(8)
        assert(results[8][3]:find("cannot read", 1, true))

        -- image.nvim is optional; without it there is no preview.
        package.loaded.image = nil
        assert(pdf_preview.available() == nil)
        local calls = {}
        local image = {
            from_file = function(file, opts)
                calls[#calls + 1] = { file, opts }
                return {
                    render = function()
                        calls[#calls + 1] = "render"
                    end,
                    clear = function()
                        calls[#calls + 1] = "clear"
                    end,
                }
            end,
        }
        package.loaded.image = image
        assert(pdf_preview.available() == image)
        local win, buf = vim.api.nvim_get_current_win(), vim.api.nvim_get_current_buf()
        local img = assert(pdf_preview.show(image, png, win, buf))
        assert(vim.deep_equal(calls, {
            {
                png,
                {
                    window = win,
                    buffer = buf,
                    x = 0,
                    y = 0,
                    width = vim.api.nvim_win_get_width(win),
                    height = vim.api.nvim_win_get_height(win),
                },
            },
            "render",
        }))
        img.clear()
        -- A PNG that image.nvim cannot read is removed from the cache.
        local from_file = image.from_file
        image.from_file = function()
            return nil
        end
        local unreadable, reason = pdf_preview.show(image, changed, win, buf)
        assert(unreadable == nil and reason:find("cannot read", 1, true))
        assert(vim.fn.filereadable(changed) == 0 and pdf_preview.available() == image)
        image.from_file = from_file
        -- image.nvim throws before setup(); previews are then disabled for the session.
        image.from_file = function()
            error("image.nvim is not setup. Call setup() first.")
        end
        local none, message = pdf_preview.show(image, png, win, buf)
        assert(none == nil and message:find("not setup", 1, true))
        assert(pdf_preview.available() == nil)
        local notified = {}
        local notify = vim.notify
        vim.notify = function(text, level)
            notified[#notified + 1] = { text, level }
        end
        pdf_preview.warn("first")
        pdf_preview.warn("second")
        vim.notify = notify
        assert(#notified == 1 and notified[1][1]:find("first", 1, true) and notified[1][2] == vim.log.levels.WARN)
    end)
    vim.system, pdf_preview.converter, pdf_preview.cache_dir = system, converter, cache_dir
    package.loaded.image = nil
    pdf_preview.reset()
    assert(ok, err)

    -- A real conversion with ImageMagick and Ghostscript, when installed.
    if vim.fn.executable("gs") == 1 and pdf_preview.converter() then
        pdf_preview.cache_dir = function()
            return root .. "/real-cache"
        end
        local sample = root .. "/sample.pdf"
        local made = vim.system({ pdf_preview.converter(), "-size", "20x30", "xc:red", sample }):wait()
        assert(made.code == 0, made.stderr)
        local png, failure
        pdf_preview.rasterize(sample, { density = 72 }, function(result, message)
            png, failure = result or false, message
        end)
        assert(vim.wait(20000, function()
            return png ~= nil
        end), "ImageMagick did not finish")
        assert(png and vim.fn.readblob(png):sub(2, 4) == "PNG", failure)
        pdf_preview.cache_dir = cache_dir
        pdf_preview.reset()
    end
    vim.fn.delete(root, "rf")
end

local function run()
    local note = notes.parse("/workspace/topic.norg", "topic.norg", ([=[
@document.meta
    title: Release Plan (v2)
    authors: [
        Ada Lovelace
        Grace Hopper
    ]
    categories: dev/research
    project: [New Website]
    effort: 42
    created: 2024-02-29T21:14:00+0200
    updated: 2025-03-01
    hidden: do not match me
    object: {
        list: [
            nested
        ]
        secret: not a top level key
    }
@end
@code norg
@document.meta
literal markup example
@end
draft: next steps | "quoted"; café; mixed É and [brackets].
]=]):gsub("\n", "\r\n"))

    -- @document.meta is only used for the title; metadata comes from the indexes.
    assert(vim.tbl_isempty(note.metadata))
    note.metadata = {
        authors = texts("Ada Lovelace", "Grace Hopper"),
        categories = texts("dev/research"),
        created = texts("2024-02-29"),
        updated = texts("2025-03-01"),
    }

    local function match(prompt, implicit)
        return query.match(note, assert(query.parse(prompt), prompt), implicit ~= false)
    end

    local rows, title = match([[title:"Release Plan" content:"next steps" created:2024/02/29 content:literal]])
    assert(title and #rows == 2)
    assert(rows[1].lnum == 22 and rows[1].text == "literal markup example")
    assert(rows[2].lnum == 24 and rows[2].text == [[draft: next steps | "quoted"; café; mixed É and [brackets].]])
    local hits = rows[2].hits
    assert(hits[1].text:sub(hits[1].first, hits[1].last) == "Release Plan")
    assert(hits[2].label == "created" and hits[2].text:sub(hits[2].first, hits[2].last) == "2024-02-29")
    assert(hits[3].text:sub(hits[3].first, hits[3].last) == "next steps")
    rows = match("content:literal missing | release | content:draft | content:steps")
    assert(#rows == 2 and rows[1].lnum == nil and rows[2].lnum == 24)
    assert(rows[1].text == "Release Plan (v2)")
    rows = match("authors:ada")
    assert(#rows == 1 and rows[1].lnum == nil and rows[1].hits[1].label == "authors")
    rows = match("content:missing | content:draft", false)
    assert(#rows == 1 and rows[1].lnum == 24)
    rows = match("release")
    assert(#rows == 1 and rows[1].lnum == nil)
    local preference = notes.parse("/workspace/preference.norg", "preference.norg", "preference")
    rows = query.match(preference, query.parse("preference"), true)
    assert(#rows == 1 and rows[1].lnum == nil)
    rows = query.match(preference, query.parse("preference | content:preference"), true)
    assert(#rows == 2 and rows[1].lnum == nil and rows[2].lnum == 1)
    assert(match([[draft missing|title:"release plan"]]))
    assert(not match([[missing|draft missing]]))
    assert(match([["steps | \"quoted\""]]))
    assert(match("CAFÉ [brackets]"))
    assert(match([[author:"ada lovelace" authors:hopper category:research categories:dev]]))
    -- Only indexed metadata is searchable; other keys make the query invalid.
    for _, prompt in ipairs({ [[project:"new website"]], "effort:42", [[hidden:"do not match me"]], "secret:top" }) do
        assert(not query.parse(prompt), prompt)
    end
    assert(not match([["do not match me"]]))
    assert(not match([[content:"do not match me"]]))
    assert(match([[content:"literal markup example"]]))
    assert(not match("draft", false))
    assert(match("content:draft", false))
    assert(match("release", false))
    assert(match("created:2024 created:2024/02 updated:2025/03/01"))
    assert(match("updated:2025-03"))
    -- Time of day is not indexed.
    assert(not match("created:21:14"))
    assert(not match("created:2025|updated:2025/04"))
    assert(not query.parse("year:2024|month:02|date:2024-02-29"))
    assert(match("category:dev/research"))
    assert(not match("category:dev-research"))
    local slash_date = notes.parse("/workspace/slash.norg", "slash.norg", "")
    slash_date.metadata = { updated = texts("2025/03/01") }
    local slash_rows = query.match(slash_date, query.parse("updated:2025-03-01"), true)
    local slash_hit = slash_rows[1].hits[1]
    assert(slash_hit.text:sub(slash_hit.first, slash_hit.last) == "2025/03/01")
    assert(not match("release -draft"))
    assert(match("release -draft", false))
    assert(not match("release -content:draft", false))
    assert(not match([[release -"next steps"]]))
    assert(not match([[-author:"Grace Hopper"]]))
    assert(not match("-created:2024/02"))
    rows, title = match("-created:2025 -category:archived")
    assert(#rows == 1 and not title and rows[1].lnum == nil and #rows[1].hits == 0)
    rows, title = match("release -draft | content:literal -category:archived")
    assert(#rows == 1 and not title and rows[1].lnum == 22 and #rows[1].hits == 1)
    local literal_dash = notes.parse("/workspace/dash.norg", "dash.norg", "-draft pre-release")
    assert(query.match(literal_dash, query.parse([["-draft" pre-release]]), true))
    local invalid = {
        "-", "release -", "- draft", "-title:", "-updated:",
        "", "title:", "title: release", "one|", "|one", "one||two",
        "\"unfinished", "\"\"", "\"foo\"bar", "created:",
    }
    for _, prompt in ipairs(invalid) do
        assert(not query.parse(prompt), prompt)
    end

    local root = vim.fn.tempname()
    vim.fn.mkdir(root .. "/nested", "p")
    vim.fn.mkdir(root .. "/generated/categories/deep", "p")
    vim.fn.mkdir(root .. "/generated/categories-extra", "p")
    vim.fn.writefile({ "generator" }, root .. "/generated/main.norg")
    vim.fn.writefile({ "generator" }, root .. "/generated/categories/deep/sub.norg")
    vim.fn.writefile({ "ordinary" }, root .. "/generated/categories-extra/main.norg")
    vim.fn.writefile({ "ordinary" }, root .. "/nested/main.norg")
    vim.fn.writefile({ "ordinary" }, root .. "/index.norg")
    vim.fn.writefile({ "savedonly" }, root .. "/nested/fallback.norg")
    vim.fn.writefile({ "ignored" }, root .. "/ignore.txt")
    assert(vim.uv.fs_symlink("nested", root .. "/link"))
    assert(vim.uv.fs_symlink("nested/fallback.norg", root .. "/linked.norg"))
    local buf = vim.api.nvim_get_current_buf()
    vim.api.nvim_buf_set_name(buf, root .. "/nested/fallback.norg")
    vim.api.nvim_buf_set_lines(buf, 0, -1, false, { "unsavedonly" })
    local before = #vim.api.nvim_list_bufs()
    local function scan(excluded, metadata)
        local snapshot
        notes.scan(root, excluded, function()
            return true
        end, function(results)
            snapshot = results
        end, metadata)
        assert(vim.wait(2000, function()
            return snapshot ~= nil
        end), "scan timed out")
        return snapshot
    end
    local scanned = {}
    local scandir = vim.uv.fs_scandir
    vim.uv.fs_scandir = function(path, ...)
        scanned[path] = true
        return scandir(path, ...)
    end
    local snapshot = scan(
        { "./generated/categories/../main.norg", "generated//./categories/" },
        { ["nested/main.norg"] = { categories = texts("indexed") } }
    )
    vim.uv.fs_scandir = scandir
